class User {
  final int id;
  final String name;
  final String email;
  final String gender;
  final String dob;
  final String address;
  final String message;

  const User({
    required this.id,
    required this.name,
    required this.email,
    required this.gender,
    required this.dob,
    required this.address,
    required this.message,
  });
}
